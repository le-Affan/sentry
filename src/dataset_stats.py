#!/usr/bin/env python3
"""
Summarise the generated corpus and write docs/DATASET_STATS.md.

Everything here is measured, not asserted: severity and technique distributions
with their majority-class baselines, real Qwen2.5 token lengths for both halves
of each pair, the rate of the "insufficient evidence" root-cause fallback, and a
grounding sweep for entities that appear in a report but not in its blob.

The grounding sweep is the one that matters. A reference report naming a host
that is not in its own telemetry teaches the fine-tuned model to hallucinate, and
the grounding metric in SCOPE.md 5.1 would then be scored against a corpus that
already fails it.
"""

import json
import statistics
import sys
from collections import Counter

from src import config as c
from src.generate_reports import ENTITY_RE, SECTION_RE

REPORTS = c.PROCESSED / "reports.jsonl"
BLOBS = c.PROCESSED / "blobs.jsonl"
OUT = c.DOCS / "DATASET_STATS.md"

FALLBACK = "Insufficient evidence in the available telemetry to determine root cause."


def load_tokenizer():
    from transformers import AutoTokenizer

    return AutoTokenizer.from_pretrained(c.BASE_MODEL)


def severity_of(report):
    m = SECTION_RE["severity"].search(report)
    if not m:
        return None
    first = m.group(1).strip().splitlines()[0] if m.group(1).strip() else ""
    for level in c.SEVERITY_LEVELS:
        if first.lower().startswith(level.lower()):
            return level
    return None


def ungrounded_entities(report, blob):
    """Entities in the report that do not appear verbatim in its blob."""
    out = []
    for kind, pat in ENTITY_RE.items():
        in_blob = set(pat.findall(blob))
        for ent in set(pat.findall(report)):
            if ent not in in_blob:
                out.append((kind, ent))
    return out


def pct(n, d):
    return f"{100.0 * n / d:.1f}%" if d else "n/a"


def main():
    if not REPORTS.exists():
        sys.exit(f"missing {REPORTS}")
    reports = [json.loads(x) for x in REPORTS.read_text(encoding="utf-8").splitlines() if x.strip()]
    blobs = {
        b["incident_id"]: b
        for b in (json.loads(x) for x in BLOBS.read_text(encoding="utf-8").splitlines())
    }

    tok = load_tokenizer()
    n = len(reports)

    sev = Counter()
    tech_train, tech_test = Counter(), Counter()
    rep_tokens, blob_tokens = [], []
    fallback_n = 0
    offenders = []

    for r in reports:
        b = blobs[r["incident_id"]]
        sev[severity_of(r["report"]) or "UNPARSED"] += 1
        (tech_test if r["split"] == "test" else tech_train)[r["attack_id"]] += 1
        rep_tokens.append(len(tok.encode(r["report"])))
        blob_tokens.append(b["tokens"])
        if FALLBACK in r["report"]:
            fallback_n += 1
        bad = ungrounded_entities(r["report"], b["blob"])
        if bad:
            offenders.append((r["incident_id"], r["attack_id"], bad))

    rep_tokens.sort()
    blob_tokens.sort()

    def q(v, p):
        return v[min(len(v) - 1, int(p * len(v)))]

    L = []
    W = L.append
    W("# DATASET STATS")
    W("")
    W("Generated by `src/dataset_stats.py` over `data/processed/reports.jsonl`.")
    W(f"Token counts use the real `{c.BASE_MODEL}` tokenizer, not an estimate.")
    W("")
    W(f"**{n} reference pairs.**")
    W("")
    W("---")
    W("")

    # --- severity --------------------------------------------------------
    W("## 1. Severity distribution")
    W("")
    W("| Severity | Reports | Share |")
    W("|---|---|---|")
    for k in list(c.SEVERITY_LEVELS) + ["UNPARSED"]:
        if sev.get(k):
            W(f"| {k} | {sev[k]:,} | {pct(sev[k], n)} |")
    W("")
    top_sev, top_sev_n = sev.most_common(1)[0]
    W(f"**Majority-class baseline: {pct(top_sev_n, n)} ({top_sev}).** A model predicting")
    W("`" + top_sev + "` unconditionally scores that much on severity accuracy while doing no")
    W("analysis, so SCOPE.md §5.2 requires severity accuracy to be reported against it.")
    W("")

    # --- technique -------------------------------------------------------
    W("## 2. Technique distribution")
    W("")
    W("| Technique | Train | Test | Total | Share |")
    W("|---|---|---|---|---|")
    all_tech = sorted(
        set(tech_train) | set(tech_test), key=lambda t: -(tech_train[t] + tech_test[t])
    )
    for t in all_tech:
        tot = tech_train[t] + tech_test[t]
        W(f"| `{t}` | {tech_train[t]} | {tech_test[t]} | {tot} | {pct(tot, n)} |")
    W(f"| **Total** | **{sum(tech_train.values())}** | **{sum(tech_test.values())}** | **{n}** | |")
    W("")
    tt = Counter({t: tech_train[t] + tech_test[t] for t in all_tech})
    W(
        f"**Majority-class baseline: {pct(tt.most_common(1)[0][1], n)} "
        f"({tt.most_common(1)[0][0]}).**"
    )
    missing = [t for t in all_tech if tech_test[t] == 0]
    W(f"Classes absent from the test split: {missing or 'none — split is stratified'}.")
    W("")

    # --- lengths ---------------------------------------------------------
    W("## 3. Sequence lengths")
    W("")
    W("| | Median | p90 | Max |")
    W("|---|---|---|---|")
    W(
        f"| Report tokens | {statistics.median(rep_tokens):.0f} | {q(rep_tokens, 0.9)} "
        f"| {rep_tokens[-1]} |"
    )
    W(
        f"| Blob tokens | {statistics.median(blob_tokens):.0f} | {q(blob_tokens, 0.9)} "
        f"| {blob_tokens[-1]} |"
    )
    W("")
    W(
        f"Budget check (SCOPE.md §2.7): blob cap is {c.MAX_INPUT_TOKENS}, `max_seq_len` is "
        f"{c.MAX_SEQ_LEN}."
    )
    W(
        f"Worst-case blob + report = {blob_tokens[-1]} + {rep_tokens[-1]} = "
        f"{blob_tokens[-1] + rep_tokens[-1]}, before the system prompt and chat scaffolding."
    )
    W("")

    # --- fallback --------------------------------------------------------
    W("## 4. Root-cause fallback")
    W("")
    W(f"**{fallback_n} of {n} reports ({pct(fallback_n, n)})** use the verbatim")
    W('"Insufficient evidence..." fallback required by SCOPE.md §3.5.')
    W("")
    W("This is a signal worth watching in both directions: near-zero suggests the generator")
    W("is inventing root causes it cannot support, while a high rate suggests `analyst_notes`")
    W("is not carrying enough to reason from.")
    W("")

    # --- grounding -------------------------------------------------------
    W("## 5. Grounding check")
    W("")
    W("Every hostname, IPv4, account, Windows path, and hash in each report, checked for a")
    W("verbatim appearance in that report's own blob.")
    W("")
    W(
        f"**{len(offenders)} of {n} reports ({pct(len(offenders), n)}) contain an ungrounded "
        f"entity.**"
    )
    W("")
    if offenders:
        W("| incident_id | technique | kind | entity |")
        W("|---|---|---|---|")
        for iid, aid, bad in offenders[:40]:
            for kind, ent in bad[:4]:
                W(f"| `{iid[:8]}` | `{aid}` | {kind} | `{ent}` |")
        if len(offenders) > 40:
            W("")
            W(f"({len(offenders) - 40} further offending reports not listed.)")
    else:
        W("No offenders. Every entity in every report appears verbatim in its own telemetry,")
        W("so the corpus does not itself violate the grounding metric it will be scored on.")
    W("")

    OUT.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    print(f"\nwrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
